#!/usr/bin/env python3
"""Generate the inactive browser draft schema from the authoritative P3 models."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from companion.profile_contracts import DraftDocument, Profile, MAX_DRAFT_BYTES, MAX_PROFILE_BYTES, MAX_ROWS


def generated_source():
    payload = {'draft': DraftDocument.model_json_schema(), 'profile': Profile.model_json_schema(),
               'limits': {'draftBytes': MAX_DRAFT_BYTES, 'profileBytes': MAX_PROFILE_BYTES,
                          'depth': 24, 'nodes': 40000, 'rows': MAX_ROWS}}
    return ('/* Generated by python scripts/generate_profile_schema.py; do not edit by hand. */\n'
            "(() => {\n  'use strict';\n  window.CCSDraftSchema = "
            + json.dumps(payload, ensure_ascii=True, sort_keys=True, indent=2)
            + ';\n})();\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'static/js/draft-schema.js'
    source = generated_source()
    if args.check:
        if not target.exists() or target.read_text('utf-8') != source:
            parser.exit(1, 'Draft schema is stale; regenerate it from the P3 models.\n')
        print('OK: browser draft schema matches the P3 models')
    else:
        target.write_text(source, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
